"""Factual scenario report generator.

Produces a provenance-preserving, hypothetical-label-safe report
of a collision scenario and its exposure analysis.  Every field
carries its source, model version, snapshot ID, assumptions and
limitations.  No unsupported probability or service-outage language.
"""

from __future__ import annotations

import json
from dataclasses import asdict, dataclass, field
from datetime import UTC, datetime
from typing import Any


@dataclass(frozen=True, slots=True)
class ReportProvenance:
    """Full provenance record for every section of the report."""

    kind: str  # EvidenceKind literal
    mode: str  # SourceMode literal
    source: str
    catalog_snapshot_id: str | None = None
    model_version: str | None = None
    coordinate_frame: str | None = None
    assumptions: list[str] = field(default_factory=list)
    limitations: list[str] = field(default_factory=list)


@dataclass
class ReportSection:
    """One section of the structured report."""

    title: str
    content: dict[str, Any]
    provenance: ReportProvenance


@dataclass
class ScenarioReport:
    """Complete factual scenario report."""

    schema_version: str = "1.0"
    generated_at_utc: str = ""
    scenario_id: str = ""
    scenario_type: str = "FORCED_HYPOTHETICAL"
    seed: int = 42
    sections: list[ReportSection] = field(default_factory=list)
    global_limitations: list[str] = field(default_factory=list)

    def __post_init__(self) -> None:
        if not self.generated_at_utc:
            self.generated_at_utc = datetime.now(UTC).isoformat()

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)

    def to_json(self) -> str:
        return json.dumps(self.to_dict(), indent=2, default=str)

    def to_markdown(self) -> str:
        lines: list[str] = []
        lines.append(f"# ASTRA Scenario Report — {self.scenario_id}")
        lines.append("")
        lines.append("> **⚠ HYPOTHETICAL SIMULATION — NOT A PREDICTION**")
        lines.append(f"> Scenario type: `{self.scenario_type}`")
        lines.append(f"> Generated: {self.generated_at_utc}")
        lines.append(f"> Seed: {self.seed}")
        lines.append(f"> Schema: {self.schema_version}")
        lines.append("")

        for section in self.sections:
            lines.append(f"## {section.title}")
            lines.append("")
            for key, value in section.content.items():
                if isinstance(value, list):
                    lines.append(f"**{key}:**")
                    for item in value:
                        if isinstance(item, dict):
                            parts = [f"{k}: {v}" for k, v in item.items()]
                            lines.append(f"  - {', '.join(parts)}")
                        else:
                            lines.append(f"  - {item}")
                else:
                    lines.append(f"**{key}:** {value}")
            lines.append("")
            lines.append("### Provenance")
            lines.append(f"- Kind: `{section.provenance.kind}`")
            lines.append(f"- Source: {section.provenance.source}")
            if section.provenance.catalog_snapshot_id:
                lines.append(f"- Snapshot: `{section.provenance.catalog_snapshot_id}`")
            if section.provenance.model_version:
                lines.append(f"- Model: `{section.provenance.model_version}`")
            if section.provenance.assumptions:
                lines.append("- Assumptions:")
                for a in section.provenance.assumptions:
                    lines.append(f"  - {a}")
            if section.provenance.limitations:
                lines.append("- Limitations:")
                for lim in section.provenance.limitations:
                    lines.append(f"  - {lim}")
            lines.append("")

        if self.global_limitations:
            lines.append("## Global Limitations")
            lines.append("")
            for lim in self.global_limitations:
                lines.append(f"- {lim}")
            lines.append("")

        lines.append("---")
        lines.append("*This report was generated by ASTRA Orbital Collision Lab.*")
        lines.append("*All results are from a hypothetical forced-collision simulation.*")
        lines.append("*No real-world collision prediction is implied.*")
        return "\n".join(lines)


def build_report(
    scenario_id: str,
    scenario_type: str,
    seed: int,
    participants: list[dict[str, Any]],
    modification: dict[str, Any] | None,
    occupancy: list[dict[str, Any]],
    encounters: list[dict[str, Any]],
    entry_crossings: list[dict[str, Any]],
    fragment_count: int,
    unresolved_mass_kg: float | None,
    provenance: dict[str, Any],
) -> ScenarioReport:
    """Build a complete scenario report from result data."""

    prov = ReportProvenance(
        kind=provenance.get("kind", "HYPOTHETICAL_SIMULATION"),
        mode=provenance.get("mode", "DEMO"),
        source=provenance.get("source", "unknown"),
        catalog_snapshot_id=provenance.get("catalogSnapshotId")
        or provenance.get("catalog_snapshot_id"),
        model_version=provenance.get("modelVersion") or provenance.get("model_version"),
        coordinate_frame=provenance.get("coordinateFrame") or provenance.get("coordinate_frame"),
        assumptions=provenance.get("assumptions", []),
        limitations=provenance.get("limitations", []),
    )

    sections: list[ReportSection] = []

    # 1. Participants
    sections.append(
        ReportSection(
            title="Collision Participants",
            content={
                "participants": participants,
                "scenario_type": scenario_type,
            },
            provenance=prov,
        )
    )

    # 2. Forced modification
    if modification:
        sections.append(
            ReportSection(
                title="Forced State Modification",
                content={
                    "original_separation_km": modification.get("original_separation_km"),
                    "original_state": modification.get("original_state"),
                    "modified_state": modification.get("modified_state"),
                    "note": "One participant's state was artificially modified to force a collision.",
                },
                provenance=prov,
            )
        )

    # 3. Fragment summary
    sections.append(
        ReportSection(
            title="Fragment Summary",
            content={
                "resolved_fragment_count": fragment_count,
                "unresolved_mass_kg": unresolved_mass_kg,
                "note": "Resolved fragments are a representative subset; "
                "count does not equal total physical debris.",
            },
            provenance=prov,
        )
    )

    # 4. Orbital occupancy
    sections.append(
        ReportSection(
            title="Orbital Shell Occupancy",
            content={
                "bins": occupancy,
                "note": "Fragment counts per 100-km altitude shell, derived from simulated states.",
            },
            provenance=prov,
        )
    )

    # 5. Close approaches
    sections.append(
        ReportSection(
            title="Secondary Encounters",
            content={
                "encounter_count": len(encounters),
                "encounters": encounters[:20],  # cap for readability
                "truncated": len(encounters) > 20,
                "note": "Screened encounters within modeled threshold. "
                "Distances are modeled separations, not collision probabilities.",
            },
            provenance=prov,
        )
    )

    # 6. Entry crossings
    sections.append(
        ReportSection(
            title="Atmospheric Entry Crossings",
            content={
                "crossing_count": len(entry_crossings),
                "crossings": entry_crossings,
                "note": "Fragments crossing the 120-km altitude threshold. "
                "Crossing geolocation is approximate. No ground-impact "
                "or surface damage assessment is implied.",
            },
            provenance=prov,
        )
    )

    report = ScenarioReport(
        scenario_id=scenario_id,
        scenario_type=scenario_type,
        seed=seed,
        sections=sections,
        global_limitations=[
            "All results are from a hypothetical forced-collision simulation.",
            "No real-world conjunction prediction is implied.",
            "Fragment count is a representative subset, not a physical census.",
            "Screening uses modeled trajectories with limited perturbation models.",
            "Geometric separations only — no probabilistic outcome models applied.",
            "Entry crossings do not imply surface impact or surviving fragments.",
            "Catalog data may be stale; check provenance timestamps.",
        ],
    )

    return report
